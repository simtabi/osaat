func linuxFixtureRecords() []audit.AppRecord {
	return []audit.AppRecord{
		{Name: "bash", PkgID: "bash", Source: audit.SourceDpkg, ReinstallCmd: "apt install bash"},
		{Name: "curl", PkgID: "curl", Source: audit.SourceDpkg},
		{Name: "kernel", PkgID: "kernel", Source: audit.SourceRpm},
		{Name: "vim", PkgID: "vim", Source: audit.SourcePacman},
		{Name: "firefox", PkgID: "firefox", Source: audit.SourceSnap, ReinstallCmd: "snap install firefox"},
		{Name: "Flatseal", PkgID: "com.github.tchx84.Flatseal", Source: audit.SourceFlatpak, ReinstallCmd: "flatpak install -y flathub com.github.tchx84.Flatseal"},
		// Duplicate dpkg name to test dedup
		{Name: "bash", PkgID: "bash", Source: audit.SourceDpkg},
		// Non-Linux record — should be skipped by every Linux writer
		{Name: "Safari", Source: audit.SourceSystem},
	}
}

func TestWriteAptList(t *testing.T) {
	var buf bytes.Buffer
	if err := WriteAptList(linuxFixtureRecords(), &buf); err != nil {
		t.Fatal(err)
	}
	out := buf.String()
	for _, want := range []string{
		"apt-packages.txt generated by osaat",
		"sudo apt install -y",
		"\nbash\n",
		"\ncurl\n",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("apt list missing %q\n--- output ---\n%s", want, out)
		}
	}
	// bash duplicated in input — should appear once
	if strings.Count(out, "\nbash\n") != 1 {
		t.Errorf("bash should appear once after dedup; got %d\n%s", strings.Count(out, "\nbash\n"), out)
	}
}

