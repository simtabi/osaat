func TestHasSource(t *testing.T) {
	recs := linuxFixtureRecords()
	for _, src := range []audit.Source{audit.SourceDpkg, audit.SourceRpm, audit.SourcePacman, audit.SourceSnap, audit.SourceFlatpak} {
		if !HasSource(recs, src) {
			t.Errorf("HasSource(%q) should be true", src)
		}
	}
	if HasSource(recs, audit.SourceAppStore) {
		t.Error("HasSource(app_store) should be false on Linux fixture")
	}
}

func TestWriteAllIncludesLinuxLists(t *testing.T) {
	dir := t.TempDir()
	paths, err := WriteAll(linuxFixtureRecords(), dir)
	if err != nil {
		t.Fatal(err)
	}
	names := map[string]bool{}
	for _, p := range paths {
		names[lastPathSegment(p)] = true
	}
	for _, want := range []string{
		"Brewfile",
		"mas-apps.txt",
		"apt-packages.txt",
		"dnf-packages.txt",
		"pacman-packages.txt",
		"snap-list.txt",
		"flatpak-list.txt",
		"RESTORE.md",
	} {
		if !names[want] {
			t.Errorf("WriteAll should have produced %q (got %v)", want, names)
		}
	}
}

func TestWriteAllSkipsLinuxListsOnMacOnly(t *testing.T) {
	dir := t.TempDir()
	macRecords := []audit.AppRecord{
		{Name: "1Password", Source: audit.SourceBrewCask, ReinstallCmd: "brew install --cask 1password"},
	}
	paths, err := WriteAll(macRecords, dir)
	if err != nil {
		t.Fatal(err)
	}
	for _, p := range paths {
		seg := lastPathSegment(p)
		if strings.HasSuffix(seg, "packages.txt") || strings.HasSuffix(seg, "-list.txt") {
			t.Errorf("macOS-only scan should not produce %s", seg)
		}
	}
}

func lastPathSegment(p string) string {
	for i := len(p) - 1; i >= 0; i-- {
		if p[i] == '/' || p[i] == '\\' {
			return p[i+1:]
		}
	}
	return p
}
